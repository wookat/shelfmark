// Writes src/asset-versions.ts with content hashes of the browser assets so
// HTML can reference them as /app.js?v=<hash>, busting stale browser caches
// on every deploy that changes the asset. Runs as part of `npm run deploy`.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const hash = (p) => createHash("md5").update(readFileSync(p)).digest("hex").slice(0, 8);

const out = `// Generated by scripts/asset-versions.mjs — do not edit by hand.
export const ASSET_V = {
  app: "${hash("public/app.js")}",
  css: "${hash("public/styles.css")}",
} as const;
`;

writeFileSync("src/asset-versions.ts", out);
console.log("asset versions:", out.match(/"[0-9a-f]{8}"/g).join(" "));
